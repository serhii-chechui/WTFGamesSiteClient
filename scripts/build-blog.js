#!/usr/bin/env node
/*
 * Static blog generator.
 *
 * Reads content/blog/*.md (front matter + Markdown) and writes plain HTML:
 *   public/blog/index.html            - article list, newest first
 *   public/blog/<slug>/index.html     - one page per article
 * and refreshes the managed block in public/sitemap.xml.
 *
 * Why static HTML: the site is a client-rendered SPA, and social crawlers
 * (LinkedIn, Reddit, Telegram) do not run JavaScript, so every article needs
 * its own <title> and Open Graph tags in the served HTML.
 *
 * Drafts (`draft: true`) are skipped unless `--drafts` is passed. When
 * included they get <meta name="robots" content="noindex"> and are never
 * added to the sitemap.
 *
 * Usage: node scripts/build-blog.js [--drafts]
 */
const fs = require("fs");
const path = require("path");
const matter = require("gray-matter");
const { marked } = require("marked");

const ROOT = path.resolve(__dirname, "..");
const CONTENT_DIR = path.join(ROOT, "content", "blog");
const OUT_DIR = path.join(ROOT, "public", "blog");
const SITEMAP = path.join(ROOT, "public", "sitemap.xml");
const ORIGIN = "https://www.wtfgames.com.ua"; // same origin as sitemap.xml and index.html
const SITE_NAME = "WTFGames";
const SM_START = "<!-- blog:start (generated by scripts/build-blog.js, do not edit) -->";
const SM_END = "<!-- blog:end -->";

// Font Awesome brand icons are inlined so blog pages do not need the CRA bundle or the font.
function brandIcon(name) {
    const file = path.join(ROOT, "node_modules", "@fortawesome", "fontawesome-free", "svgs", "brands", `${name}.svg`);
    return fs
        .readFileSync(file, "utf8")
        .replace(/<!--[\s\S]*?-->/g, "")
        .replace("<svg ", '<svg aria-hidden="true" focusable="false" ')
        .trim();
}
const SOCIAL = [
    ["Instagram", "instagram", "https://www.instagram.com/wtfgames_community/"],
    ["LinkedIn", "linkedin", "https://www.linkedin.com/groups/8502086/"],
    ["Twitter", "twitter", "https://x.com/wtfgames14?s=21"],
];

const includeDrafts = process.argv.includes("--drafts");

const esc = (value) =>
    String(value)
        .replace(/&/g, "&amp;")
        .replace(/</g, "&lt;")
        .replace(/>/g, "&gt;")
        .replace(/"/g, "&quot;")
        .replace(/'/g, "&#39;");

function fail(file, message) {
    throw new Error(`${path.relative(ROOT, file)}: ${message}`);
}

function toIsoDate(value, file) {
    const date = value instanceof Date ? value : new Date(String(value));
    if (Number.isNaN(date.getTime())) fail(file, `invalid date "${value}"`);
    return date.toISOString().slice(0, 10);
}

function formatDate(iso) {
    return new Date(`${iso}T00:00:00Z`).toLocaleDateString("en-US", {
        year: "numeric",
        month: "long",
        day: "numeric",
        timeZone: "UTC",
    });
}

/** Resolve a path relative to the article folder into a root-relative URL. */
function assetUrl(slug, src) {
    if (/^([a-z][a-z0-9+.-]*:|\/\/|\/|#)/i.test(src)) return src;
    return `/blog/${slug}/${src}`;
}

function loadArticles() {
    if (!fs.existsSync(CONTENT_DIR)) return [];
    const articles = [];
    for (const name of fs.readdirSync(CONTENT_DIR).filter((f) => f.endsWith(".md"))) {
        const file = path.join(CONTENT_DIR, name);
        const { data, content } = matter(fs.readFileSync(file, "utf8"));
        for (const key of ["title", "description", "date", "slug", "cover"]) {
            if (!data[key]) fail(file, `missing front matter field "${key}"`);
        }
        if (data.draft !== true && /TODO/.test(content)) fail(file, "published article still contains a TODO marker");
        const slug = String(data.slug);
        if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(slug)) fail(file, `invalid slug "${slug}"`);
        articles.push({
            title: String(data.title),
            description: String(data.description),
            date: toIsoDate(data.date, file),
            slug,
            cover: assetUrl(slug, String(data.cover)),
            coverAlt: data.coverAlt ? String(data.coverAlt) : String(data.title),
            lang: data.lang ? String(data.lang) : "en",
            tags: Array.isArray(data.tags) ? data.tags.map(String) : [],
            draft: data.draft === true,
            body: content,
        });
    }
    const slugs = new Set();
    for (const a of articles) {
        if (slugs.has(a.slug)) throw new Error(`duplicate slug "${a.slug}"`);
        slugs.add(a.slug);
    }
    return articles
        .filter((a) => includeDrafts || !a.draft)
        .sort((a, b) => (a.date < b.date ? 1 : a.date > b.date ? -1 : a.slug.localeCompare(b.slug)));
}

function renderBody(article) {
    let html = marked.parse(article.body, { gfm: true });
    // Root-relative image URLs, lazy loading, scrollable tables.
    html = html.replace(/<img ([^>]*?)src="([^"]+)"/g, (_m, pre, src) => {
        return `<img loading="lazy" decoding="async" ${pre}src="${esc(assetUrl(article.slug, src.replace(/&amp;/g, "&")))}"`;
    });
    html = html.replace(/<table>/g, '<div class="table-wrap"><table>').replace(/<\/table>/g, "</table></div>");
    return html;
}

