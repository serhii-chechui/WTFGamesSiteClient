function articleHtml(a) {
    const url = `${ORIGIN}/blog/${a.slug}/`;
    const image = a.cover.startsWith("http") ? a.cover : ORIGIN + a.cover;
    const jsonLd = {
        "@context": "https://schema.org",
        "@type": "BlogPosting",
        headline: a.title,
        description: a.description,
        datePublished: a.date,
        image: [image],
        mainEntityOfPage: url,
        inLanguage: a.lang,
        author: { "@type": "Organization", name: SITE_NAME },
        publisher: { "@type": "Organization", name: SITE_NAME, logo: { "@type": "ImageObject", url: `${ORIGIN}/logo512.png` } },
    };
    const head = [
        `<meta property="og:type" content="article">`,
        `<meta property="og:site_name" content="${SITE_NAME}">`,
        `<meta property="og:title" content="${esc(a.title)}">`,
        `<meta property="og:description" content="${esc(a.description)}">`,
        `<meta property="og:url" content="${esc(url)}">`,
        `<meta property="og:image" content="${esc(image)}">`,
        `<meta property="article:published_time" content="${a.date}">`,
        ...a.tags.map((t) => `<meta property="article:tag" content="${esc(t)}">`),
        `<meta name="twitter:card" content="summary_large_image">`,
        `<meta name="twitter:title" content="${esc(a.title)}">`,
        `<meta name="twitter:description" content="${esc(a.description)}">`,
        `<meta name="twitter:image" content="${esc(image)}">`,
        // "<" is escaped so front-matter text can never close the script element.
        `<script type="application/ld+json">${JSON.stringify(jsonLd).replace(/</g, "\\u003c")}</script>`,
    ].join("\n");
    const tags = a.tags.length
        ? `<ul class="tags" aria-label="Tags">${a.tags.map((t) => `<li>${esc(t)}</li>`).join("")}</ul>`
        : "";
    const draftNote = a.draft
        ? `<p class="draft-note" role="note"><span class="badge">Draft</span> This article is not published. It is hidden from search engines and the sitemap, and is only generated for local preview.</p>`
        : "";
    const bodyHtml = `<main>
<article>
${draftNote}
<h1>${esc(a.title)}</h1>
<p class="meta"><time datetime="${a.date}">${formatDate(a.date)}</time></p>
${tags}
<figure class="cover"><img src="${esc(a.cover)}" alt="${esc(a.coverAlt)}" width="1200" height="630"></figure>
${renderBody(a)}
</article>
<hr>
<p><a href="/blog/">&larr; All articles</a></p>
</main>`;
    return layout({
        lang: a.lang,
        title: `${a.title} | ${SITE_NAME}`,
        description: a.description,
        canonical: url,
        robots: a.draft ? "noindex, nofollow" : "",
        head,
        bodyHtml,
        current: "/blog/",
    });
}

function indexHtml(articles) {
    const url = `${ORIGIN}/blog/`;
    const description = "Articles from WTFGames: practical notes on our apps and the problems they solve.";
    const head = [
        `<meta property="og:type" content="website">`,
        `<meta property="og:site_name" content="${SITE_NAME}">`,
        `<meta property="og:title" content="Blog | ${SITE_NAME}">`,
        `<meta property="og:description" content="${esc(description)}">`,
        `<meta property="og:url" content="${url}">`,
        `<meta property="og:image" content="${ORIGIN}/logo512.png">`,
        `<meta name="twitter:card" content="summary">`,
    ].join("\n");
    const items = articles
        .map(
            (a) => `<li class="post-card"><article>
<a href="/blog/${a.slug}/" tabindex="-1" aria-hidden="true"><img src="${esc(a.cover)}" alt="" width="1200" height="630" loading="lazy" decoding="async"></a>
<h2><a href="/blog/${a.slug}/">${esc(a.title)}</a>${a.draft ? ' <span class="badge">Draft</span>' : ""}</h2>
<p class="meta"><time datetime="${a.date}">${formatDate(a.date)}</time></p>
<p>${esc(a.description)}</p>
</article></li>`
        )
        .join("\n");
    const bodyHtml = `<main>
<h1>Blog</h1>
${articles.length ? `<ul class="post-list">\n${items}\n</ul>` : "<p>No articles yet.</p>"}
</main>`;
    // An index that only lists drafts must not be indexed either.
    const allDrafts = articles.length > 0 && articles.every((a) => a.draft);
    return layout({
        lang: "en",
        title: `Blog | ${SITE_NAME}`,
        description,
        canonical: url,
        robots: allDrafts || articles.length === 0 ? "noindex, follow" : "",
        head,
        bodyHtml,
        current: "/blog/",
    });
}

function cleanOutput() {
    // Remove only previously generated HTML; committed assets (images) stay.
    if (!fs.existsSync(OUT_DIR)) return;
    fs.rmSync(path.join(OUT_DIR, "index.html"), { force: true });
    for (const entry of fs.readdirSync(OUT_DIR, { withFileTypes: true })) {
        if (entry.isDirectory()) fs.rmSync(path.join(OUT_DIR, entry.name, "index.html"), { force: true });
    }
}

function updateSitemap(published) {
    const xml = fs.readFileSync(SITEMAP, "utf8");
    const start = xml.indexOf(SM_START);
    const end = xml.indexOf(SM_END);
    if (start === -1 || end === -1 || end < start) {
        throw new Error(`public/sitemap.xml must contain the markers:\n${SM_START}\n${SM_END}`);
    }
    const entry = (loc, lastmod, changefreq, priority) =>
        `    <url>\n        <loc>${loc}</loc>\n        <lastmod>${lastmod}</lastmod>\n        <changefreq>${changefreq}</changefreq>\n        <priority>${priority}</priority>\n    </url>\n`;
    let block = "";
    if (published.length) {
        block += entry(`${ORIGIN}/blog/`, published[0].date, "weekly", "0.6");
        for (const a of published) block += entry(`${ORIGIN}/blog/${a.slug}/`, a.date, "monthly", "0.7");
    }
    const next = `${xml.slice(0, start)}${SM_START}\n${block}    ${xml.slice(end)}`;
    if (next !== xml) fs.writeFileSync(SITEMAP, next);
}

function main() {
    const articles = loadArticles();
    cleanOutput();
    fs.mkdirSync(OUT_DIR, { recursive: true });
    for (const a of articles) {
        const dir = path.join(OUT_DIR, a.slug);
        fs.mkdirSync(dir, { recursive: true });
        fs.writeFileSync(path.join(dir, "index.html"), articleHtml(a));
    }
    fs.writeFileSync(path.join(OUT_DIR, "index.html"), indexHtml(articles));
    updateSitemap(articles.filter((a) => !a.draft));
    const drafts = articles.filter((a) => a.draft).length;
    console.log(
        `blog: ${articles.length} article(s) generated (${drafts} draft${drafts === 1 ? "" : "s"}${includeDrafts ? ", drafts included" : ", drafts excluded"})`
    );
}

main();
